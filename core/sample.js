/** 96 glyphs × 8 bytes, codes 32–127. Decode with width 8, height 8, ASCII preset, first code 32. */
export function sampleFontBytes() {
  const lines = G.trim().split('\n');
  const out = new Uint8Array(lines.length * 8);
  lines.forEach((line, i) => {
    line.trim().split(/\s+/).forEach((row, r) => {
      out[i * 8 + r] = parseInt(row, 2) << 2; // 5 px wide placed in columns 1–5
    });
  });
  return out;
}
