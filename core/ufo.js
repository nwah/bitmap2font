// UFO 3 source writer (RoboFont / FontForge / fontmake compatible).

import { ufoFileName } from './names.js';
import { postscriptName } from './font.js';
import { makeZip } from './zip.js';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function plistValue(v, ind) {
  const pad = '\t'.repeat(ind);
  if (Array.isArray(v)) {
    if (!v.length) return `${pad}<array/>`;
    return `${pad}<array>\n${v.map((x) => plistValue(x, ind + 1)).join('\n')}\n${pad}</array>`;
  }
  if (typeof v === 'boolean') return `${pad}<${v}/>`;
  if (typeof v === 'number') return Number.isInteger(v) ? `${pad}<integer>${v}</integer>` : `${pad}<real>${v}</real>`;
  if (v && typeof v === 'object') {
    const keys = Object.keys(v);
    if (!keys.length) return `${pad}<dict/>`;
    return `${pad}<dict>\n${keys.map((k) => `${pad}\t<key>${esc(k)}</key>\n${plistValue(v[k], ind + 1)}`).join('\n')}\n${pad}</dict>`;
  }
  return `${pad}<string>${esc(v)}</string>`;
}

export function plist(obj) {
  return '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n' +
    `<plist version="1.0">\n${plistValue(obj, 0)}\n</plist>\n`;
}

function glif(g) {
  const lines = ['<?xml version="1.0" encoding="UTF-8"?>', `<glyph name="${esc(g.name)}" format="2">`, `\t<advance width="${g.advance}"/>`];
  for (const c of g.codes) lines.push(`\t<unicode hex="${c.toString(16).toUpperCase().padStart(4, '0')}"/>`);
  if (g.contours.length) {
    lines.push('\t<outline>');
    for (const c of g.contours) {
      lines.push('\t\t<contour>');
      for (const p of c) lines.push(`\t\t\t<point x="${p.x}" y="${p.y}" type="line"/>`);
      lines.push('\t\t</contour>');
    }
    lines.push('\t</outline>');
  }
  lines.push('</glyph>', '');
  return lines.join('\n');
}

/**
 * Produce the files of a UFO 3 package.
 * @returns {{dirName:string, files:Array<{path:string,data:string}>}} paths relative to the .ufo directory
 */
export function buildUFOFiles(font) {
  const [maj, min] = String(font.version).split('.').map((n) => parseInt(n, 10) || 0);
  const winAscent = Math.max(font.ascender, font.bbox.yMax, 0);
  const winDescent = Math.max(-font.descender, -font.bbox.yMin, 0);
  const fontinfo = {
    familyName: font.familyName,
    styleName: font.styleName,
    styleMapFamilyName: font.familyName,
    styleMapStyleName: 'regular',
    versionMajor: maj,
    versionMinor: min,
    unitsPerEm: font.unitsPerEm,
    ascender: font.ascender,
    descender: font.descender,
    capHeight: font.capHeight,
    xHeight: font.xHeight,
    italicAngle: 0,
    openTypeHheaAscender: font.ascender,
    openTypeHheaDescender: font.descender,
    openTypeHheaLineGap: font.lineGap,
    openTypeOS2TypoAscender: font.ascender,
    openTypeOS2TypoDescender: font.descender,
    openTypeOS2TypoLineGap: font.lineGap,
    openTypeOS2WinAscent: winAscent,
    openTypeOS2WinDescent: winDescent,
    openTypeOS2Selection: [7],
    openTypeOS2WeightClass: 400,
    openTypeOS2WidthClass: 5,
    openTypeOS2Type: [],
    postscriptFontName: postscriptName(font),
    postscriptIsFixedPitch: font.isFixedPitch,
    postscriptUnderlinePosition: -font.pixelHeight,
    postscriptUnderlineThickness: font.pixelHeight,
    note: `Generated by bitmap2font from ${font.source.width}x${font.source.height} pixel bitmaps (pixel aspect ${font.settings.aspect}).`,
  };
  const used = new Set();
  const contents = {};
  const glifs = [];
  for (const g of font.glyphs) {
    const file = ufoFileName(g.name, used);
    contents[g.name] = file;
    glifs.push({ path: `glyphs/${file}`, data: glif(g) });
  }
  const files = [
    { path: 'metainfo.plist', data: plist({ creator: 'com.bitmap2font', formatVersion: 3, formatVersionMinor: 0 }) },
    { path: 'fontinfo.plist', data: plist(fontinfo) },
    { path: 'layercontents.plist', data: plist([['public.default', 'glyphs']]) },
    { path: 'lib.plist', data: plist({ 'public.glyphOrder': font.glyphs.map((g) => g.name) }) },
    { path: 'glyphs/contents.plist', data: plist(contents) },
    ...glifs,
  ];
  return { dirName: `${postscriptName(font)}.ufo`, files };
}

/** UFO package zipped into a single download (contains "<Name>.ufo/..."). */
export function buildUFOZip(font) {
  const { dirName, files } = buildUFOFiles(font);
  return makeZip(files.map((f) => ({ path: `${dirName}/${f.path}`, data: f.data })));
}
